/** Friendly time label: "Today 8:00 PM", "Tomorrow 9:00 AM", "Fri 13 Nov, 9:00 AM". */
export function whenLabel(ms: number, lang: Lang, now = new Date()): string {
  const d = new Date(ms);
  const day0 = new Date(now); day0.setHours(0, 0, 0, 0);
  const diffDays = Math.floor((new Date(d).setHours(0, 0, 0, 0) - day0.getTime()) / 86400000);
  const h = d.getHours(), m = d.getMinutes();
  const mm = m < 10 ? '0' + m : String(m);
  if (lang === 'bn') {
    const part = h < 5 ? 'রাত' : h < 12 ? 'সকাল' : h < 15 ? 'দুপুর' : h < 18 ? 'বিকাল' : h < 20 ? 'সন্ধ্যা' : 'রাত';
    const t = `${part} ${toBnDigits(h % 12 || 12)}:${toBnDigits(mm)}`;
    if (diffDays === 0) return `আজ ${t}`;
    if (diffDays === 1) return `কাল ${t}`;
    if (diffDays === -1) return `গতকাল ${t}`;
    const days = ['রবি', 'সোম', 'মঙ্গল', 'বুধ', 'বৃহস্পতি', 'শুক্র', 'শনি'];
    const months = ['জানু', 'ফেব্রু', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টে', 'অক্টো', 'নভে', 'ডিসে'];
    return `${days[d.getDay()]}, ${toBnDigits(d.getDate())} ${months[d.getMonth()]} · ${t}`;
  }
  const t = `${h % 12 || 12}:${mm} ${h < 12 ? 'AM' : 'PM'}`;
  if (diffDays === 0) return `Today ${t}`;
  if (diffDays === 1) return `Tomorrow ${t}`;
  if (diffDays === -1) return `Yesterday ${t}`;
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return `${days[d.getDay()]} ${d.getDate()} ${months[d.getMonth()]}, ${t}`;
}
